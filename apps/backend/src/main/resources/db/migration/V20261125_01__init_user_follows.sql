--
-- 归属：包 5 叶立铭
-- 依赖：sys_user（包 1 的 V1 基线中创建，本脚本不重复建用户表）
-- 说明：
--   1. 单向关注一行记录，(follower_id -> followee_id)
--   2. 双向都存在即为「互相关注」，也就是设计文档里的「好友」
--   3. is_mutual 由关注/取关时同步维护，避免查询好友可见作品时做自连接
--   4. 数据库表变更只走 Flyway，禁止手工改共享库
-- ============================================================================

CREATE TABLE IF NOT EXISTS user_follows
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT                   NOT NULL,
    followee_id BIGINT                   NOT NULL,
    is_mutual   BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- 同一对用户只允许一条关注关系：重复关注走幂等逻辑，不新增记录
    CONSTRAINT uk_user_follows_pair UNIQUE (follower_id, followee_id),
    -- 不能关注自己（服务端同时校验，这里做兜底）
    CONSTRAINT ck_user_follows_not_self CHECK (follower_id <> followee_id),
    CONSTRAINT fk_user_follows_follower FOREIGN KEY (follower_id) REFERENCES sys_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_follows_followee FOREIGN KEY (followee_id) REFERENCES sys_user (id) ON DELETE CASCADE
);

-- 粉丝列表 / 粉丝数统计：按被关注者查询
CREATE INDEX IF NOT EXISTS idx_user_follows_followee_mutual
    ON user_follows (followee_id, is_mutual);

-- 关注列表 / 关注数统计：按关注者查询（联合唯一索引已覆盖前缀，这里显式建索引保证可读性）
CREATE INDEX IF NOT EXISTS idx_user_follows_follower
    ON user_follows (follower_id);

COMMENT ON TABLE user_follows IS '用户关注关系（单向记录，双向即互关好友）';
COMMENT ON COLUMN user_follows.follower_id IS '关注发起人';
COMMENT ON COLUMN user_follows.followee_id IS '被关注人';
COMMENT ON COLUMN user_follows.is_mutual IS '是否互相关注（双向关注后置为 true）';
